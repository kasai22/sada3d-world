function productSection(entry: CatalogEntry): string[] {
  const { product, commercial } = entry;
  const launch = assessLaunch(entry, product, { now: new Date("2026-09-13T00:00:00.000Z") });
  const capability = capabilityVerdict(product.material, product.technology);
  const model = VERIFIED_MODELS.find((asset) => asset.url === product.model?.url);
  const dimensions = (product.specifications ?? [])
    .filter((row) => !/technology|layer height/i.test(row.label))
    .map((row) => `${row.label} ${row.value}`)
    .join("; ");

  const category = CATALOG_CATEGORIES.find((node) => node.value === product.browseCategory);
  const leaf = category?.children?.find((node) => node.value === product.category);

  const rows: string[][] = [
    ["Product ID", `KNOWN — ${product.id}`],
    ["Product name", `PROPOSED — ${product.name}`],
    ["SKU", fact(commercial.sku)],
    ["Slug", `KNOWN — ${product.slug}`],
    ["Category", `PROPOSED — ${category?.label ?? product.browseCategory} › ${leaf?.label ?? product.category}`],
    ["Product class", fact(commercial.productClass)],
    ["Customer", fact(commercial.customer)],
    ["Use case", fact(commercial.useCase)],
    ["Applications", `PROPOSED — ${(product.applications ?? []).join(", ") || "none"}`],
    ["Material", capability.approved ? `APPROVED — ${product.material.toUpperCase()} (business decision ledger)` : `NOT APPROVED — ${capability.reasons.join("; ")}`],
    ["Technology", isApproved("manufacturing-process", product.technology) ? `APPROVED — ${product.technology.toUpperCase()} (business decision ledger)` : `NOT APPROVED — ${product.technology.toUpperCase()}`],
    ["Colours", product.colors?.length ? `PROPOSED — ${product.colors.join(", ")} (within the approved colours; not approved for this product)` : "MISSING"],
    ["Dimensions", dimensions ? `KNOWN — ${dimensions} (measured from the model file)` : "MISSING — no dimensions recorded"],
    ["Weight", fact(commercial.weightGrams)],
    ["Manufacturing limitations", product.description ? `KNOWN — stated from the model: ${product.description}` : "MISSING"],
    ["3D model", model ? `KNOWN — ${model.url} (${model.format.toUpperCase()}, ${model.partCount} part${model.partCount === 1 ? "" : "s"}, parsed and measured)` : "MISSING"],
    ["Image", product.image ? (product.image.approval ? `APPROVED — ${product.image.src} (${product.image.approval.reference})` : `NOT APPROVED — ${product.image.src}`) : "MISSING — NO_IMAGE_YET"],
    ["Visual required", fact(commercial.visual.required)],
    ["Render specification", fact(commercial.visual.renderSpecification)],
    ["Pricing model", fact(commercial.pricingModel)],
    [
      "Price",
      product.priceStatus === "approved"
        ? `APPROVED — ${formatINR(product.price)}`
        : product.priceStatus === "quote-only"
          ? "QUOTE ONLY"
          : `PROVISIONAL — ${formatINR(product.price)}. ${entry.priceBasis} Not a commercial price.`,
    ],
    ["Price approval", entry.priceApprovals?.length ? entry.priceApprovals.map((r) => `${formatINR(r.amount)} from ${r.effectiveFrom} (${r.reference}, ${r.approvedBy})`).join("; ") : "NOT APPROVED — no price approval record"],
    ["Commercial copy", fact(commercial.copy)],
    ["Homepage feature", fact(commercial.featured)],
    ["Technical approval", launch.technical.status === "PASS" ? "PASS — validateProduct and validateCatalog" : `BLOCKING — ${launch.technical.reasons.join("; ")}`],
    ["Business approval", product.approvalStatus === "approved" && entry.approval ? `APPROVED — ${entry.approval.reference} (${entry.approval.approvedOn}, ${entry.approval.approvedBy})` : `NOT APPROVED — status ${product.approvalStatus}`],
    ["Launch status", launch.launch.ready ? "READY" : "NOT READY"],
  ];

  return [
    `### ${product.id} — ${product.name}`,
    "",
    table(["Field", "State and value"], rows),
    "",
    "**Why it cannot launch:**",
    "",
    ...(launch.launch.reasons.length ? launch.launch.reasons.map((reason) => `- ${reason}`) : ["- Nothing: launch-ready."]),
    ...(entry.contentGaps.length ? ["", "**Recorded gaps:**", "", ...entry.contentGaps.map((gap) => `- ${gap}`)] : []),
    "",
  ];
}

