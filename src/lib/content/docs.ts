/**
 * The commercial catalog documents, rendered from the canonical modules.
 *
 *   MANUFACTURING_CAPABILITY.md   ← src/content/catalog/manufacturing.ts
 *   LAUNCH_CATALOG.md             ← src/content/catalog (entries, services)
 *                                   + lib/catalog/launch.ts (status, reasons)
 *
 * Generated, never hand-edited: `npm run content:docs` writes them and
 * `npm run content:docs -- --check` (also a unit test) fails when a file differs
 * from what the code says. A document that can drift from the data is a second
 * source of truth; one that cannot is a view.
 *
 * Deterministic: no clock, no environment. The same code renders the same bytes.
 */

const HEADER = (source: string) =>
  `<!-- GENERATED by \`npm run content:docs\` from ${source}. Do not edit by hand: change the source and regenerate. -->\n`;

const isVolume = (value: unknown): value is { x: number; y: number; z: number } =>
  typeof value === "object" && value !== null && ["x", "y", "z"].every((k) => typeof (value as Record<string, unknown>)[k] === "number");

const list = (value: unknown): string =>
  Array.isArray(value)
    ? value.join("; ")
    : isVolume(value)
      ? `${value.x} × ${value.y} × ${value.z} mm`
      : typeof value === "object" && value
        ? JSON.stringify(value)
        : String(value);

const MATERIAL_NAMES: Record<string, string> = { pla: "PLA", petg: "PETG", tpu: "TPU", abs: "ABS", resin: "Resin" };
const decided = (kind: "material" | "manufacturing-process", subjects: readonly string[], outcome: "APPROVED" | "NOT_APPROVED") =>
  subjects.filter((subject) => decisionFor(kind, subject)?.decision === outcome);

/** Escaping for table cells happens once, in `cell`. */
const fact = (value: Fact<unknown>): string => describeFact(value, list as never);

const factValueList = (value: Fact<unknown>): string[] =>
  value.state === "APPROVED" || value.state === "KNOWN" || value.state === "PROPOSED"
    ? (Array.isArray(value.value) ? value.value : [value.value]).map(String)
    : [];

const STATUS_TEXT = { AVAILABLE: "AVAILABLE", COMING_SOON: "COMING SOON", UNAVAILABLE: "UNAVAILABLE" } as const;

/** One kind's capabilities as "PLA — AVAILABLE; ABS — COMING SOON". */
const statusList = (kind: CapabilityKind, status?: keyof typeof STATUS_TEXT) =>
  capabilities(kind)
    .filter((row) => !status || row.status === status)
    .map((row) => (status ? row.label : `${row.label} — ${STATUS_TEXT[row.status]}`))
    .join(", ") || "none";

/** The three-state explanation, shared by all three documents' generated parts. */
const CAPABILITY_STATES = [
  "- **AVAILABLE** — approved by a Reality 3D business decision (a ledger record with a reference, an approver and a date). The only state that can be selected, quoted, carted, ordered, or used by a publishable product.",
  "- **COMING SOON** — planned, on the roadmap (`src/content/catalog/roadmap.json`), and **not approved**. Shown to customers as a future capability, muted and badged. The quote engine, cart, checkout and order creation refuse it; a product using it cannot be published or launch. A roadmap entry has no approver, no date and no specification — it is not an approval and cannot become one.",
  "- **UNAVAILABLE** — not approved and not planned. Not shown as an option.",
  "",
  "Capability status is about what Reality 3D can make. It is separate from Payload draft/published, from product approval, from technical validity and from price approval, which are questions about a product.",
];

const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\n/g, " ");

const approvalLabel = (approval: { state: string; approval?: { reference: string; approvedOn: string } }) =>
  approval.state === "APPROVED" && approval.approval
    ? `APPROVED — ${approval.approval.reference} (${approval.approval.approvedOn})`
    : "NOT APPROVED";

function table(headers: readonly string[], rows: readonly (readonly string[])[]): string {
  return [
    `| ${headers.join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.map(cell).join(" | ")} |`),
  ].join("\n");
}

/** The state of a decision spread over several facts: approved only if all are. */
function aggregate(states: readonly FactState[]): FactState {
  if (states.length > 0 && states.every((state) => state === "APPROVED")) return "APPROVED";
  if (states.some((state) => state === "BLOCKED")) return "BLOCKED";
  if (states.some((state) => state === "PROPOSED" || state === "KNOWN")) return "PROPOSED";
  return "MISSING";
}

